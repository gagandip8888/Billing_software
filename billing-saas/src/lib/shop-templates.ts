// Target dictionary object supporting direct SHOP_TEMPLATES[shopType] lookup
export const SHOP_TEMPLATES: Record<
  string,
  ShopTemplate & { invoiceFields: ProductFieldDefinition[] }
> = new Proxy(TEMPLATES as any, {
  get(target, prop: string) {
    if (typeof prop !== "string") return undefined;
    const upper = prop.toUpperCase().replace(/-/g, "_");
    if (target[upper]) return target[upper];
    if (target[prop]) return target[prop];
    const aliasKey = ALIASES[prop.toLowerCase()];
    if (aliasKey && target[aliasKey]) return target[aliasKey];
    return target.CUSTOM;
  },
});

// Helper for explicit retrieval with safe fallback
export function getShopTemplate(
  shopType?: string | null
): ShopTemplate & { invoiceFields: ProductFieldDefinition[] } {
  if (!shopType) return TEMPLATES.CUSTOM as any;
  const key = shopType.toUpperCase().replace(/-/g, "_");
  return (TEMPLATES[key] || SHOP_TEMPLATES[shopType] || TEMPLATES.CUSTOM) as any;
}

